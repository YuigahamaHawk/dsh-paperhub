/** Resolve the dictionary for a host locale id. */
export function dictFor(localeId) {
  const id = String(localeId ?? '').toLowerCase()
  if (id.startsWith('zh')) return ZH
  return EN
}

/** Extract the active locale id from a DSH locale snapshot. */
export function localeIdOf(snapshot) {
  if (snapshot === null || typeof snapshot !== 'object') return 'en'
  for (const key of ['active', 'id', 'locale', 'language']) {
    if (typeof snapshot[key] === 'string' && snapshot[key] !== '') return snapshot[key]
  }
  return 'en'
}

/** Create a translator bound to the host locale (reads the live locale on every call). */
export function createT(ctx) {
  let override = 'auto'
  const currentLocale = () => {
    if (override === 'en' || override === 'zh-CN') return override
    try {
      return localeIdOf(ctx?.locale?.getLocale?.())
    } catch {
      return 'en'
    }
  }
  const t = (key, fallback, vars) => {
    const localeId = currentLocale()
    const dict = dictFor(localeId)
    let value = dict[key]
    if (value === undefined) {
      if (typeof fallback === 'string') value = fallback
      else if (fallback && typeof fallback === 'object') value = fallback[localeId] ?? fallback.en ?? key
      else value = key
    }
    if (typeof value === 'function') return value(vars)
    if (vars && typeof value === 'string') {
      return value.replace(/\{(\w+)\}/g, (match, name) => (vars[name] === undefined ? match : String(vars[name])))
    }
    return value
  }
  Object.defineProperty(t, 'locale', {
    get: currentLocale,
    enumerable: true,
  })
  /** Reader-local UI language override: 'auto' | 'en' | 'zh-CN'. */
  t.setLocaleOverride = (value) => {
    override = value === 'en' || value === 'zh-CN' ? value : 'auto'
  }
  t.dict = DICTS.en
  t.dictionaries = DICTS
  return t
}
