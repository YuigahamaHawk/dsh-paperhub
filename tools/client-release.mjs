// Validate the exact browser artifact before replacing the file watched by DSH.
import { execFileSync } from 'node:child_process'
import { createHash, randomUUID } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { Script } from 'node:vm'
import { setTimeout as delay } from 'node:timers/promises'

/** Keep module-initialization errors inside the Reader instead of failing DSH web boot. */
export function wrapClient({ name, version, code }) {
  return `/* ${name} ${version} — generated by build.mjs; do not edit */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(name)},
  factory(require) {
    try {
      var module = { exports: {} };
      var exports = module.exports;
      globalThis.__dshReaderRequire = require;
      (function (module, exports, require) {
${code}
      })(module, exports, require);
      if (typeof module.exports.apply !== 'function') throw new Error('Reader client did not export apply()');
      return module.exports;
    } catch (error) {
      const failure = {
        message: String(error && error.message || error),
        stack: String(error && error.stack || '').slice(0, 2000),
      };
      console.error('[dsh-reader] client module failed:', error);
      return {
        __readerBootFailure: failure,
        inject: ['slots'],
        apply(ctx) {
          try {
            const React = require('react');
            const h = React.createElement;
            ctx.slots.inject('sidebar.panellist', () => ctx.slots.register(
              { name: 'sidebar.panellist', id: 'reader', order: 5, label: () => '阅读器（加载失败）' },
              () => h('span', { 'aria-hidden': true }, '!'),
            ));
            ctx.slots.inject('main', () => ctx.slots.register(
              { name: 'main', key: 'reader' },
              () => h('section', { role: 'alert', style: { padding: '32px', maxWidth: '800px' } },
                h('h2', null, '阅读器暂时无法加载'),
                h('p', null, 'DSH 的其他功能仍可使用。请修复阅读器插件并重新构建。'),
                h('pre', { style: { whiteSpace: 'pre-wrap' } }, failure.message),
              ),
            ));
            Promise.resolve(fetch('/api/dsh-reader/rpc', {
              method: 'POST', credentials: 'same-origin',
              headers: { 'content-type': 'application/json' },
              body: JSON.stringify({ method: 'diag.report', params: { kind: 'client-module-failed', payload: failure } }),
            })).catch(() => undefined);
          } catch (reportError) {
            console.error('[dsh-reader] could not show load failure:', reportError);
          }
        },
      };
    }
  },
});
`
}

/** esbuild does not parse RegExp bodies; V8 must also compile the generated JS. */
export function validateClient(source, { filename = 'client.js', smokeTest } = {}) {
  new Script(source, { filename })
  if (smokeTest !== undefined) {
    try {
      return execFileSync(process.execPath, [smokeTest, '-'], {
        input: source, encoding: 'utf8', timeout: 15000,
        maxBuffer: 2 * 1024 * 1024, windowsHide: true,
        stdio: ['pipe', 'pipe', 'pipe'],
      })
    } catch (error) {
      throw new Error(`Reader candidate failed its activation check; live client.js was not replaced.\n${error.stderr || error.stdout || error.message}`, { cause: error })
    }
  }
}

/** Rename a complete sibling file over the destination; never truncate a live artifact. */
export async function writeAtomic(filename, contents) {
  const bytes = Buffer.isBuffer(contents) ? contents : Buffer.from(contents)
  if (existsSync(filename) && readFileSync(filename).equals(bytes)) return false
  mkdirSync(dirname(filename), { recursive: true })
  const temporary = join(dirname(filename), `.${filename.split(/[\\/]/).pop()}.${randomUUID()}.tmp`)
  try {
    writeFileSync(temporary, bytes, { flag: 'wx' })
    for (let attempt = 0; ; attempt++) {
      try {
        renameSync(temporary, filename)
        return true
      } catch (error) {
        if (!['EACCES', 'EBUSY', 'EPERM'].includes(error.code) || attempt >= 6) throw error
        await delay(Math.min(20 * 2 ** attempt, 200))
      }
    }
  } finally {
    rmSync(temporary, { force: true })
  }
}

/** Failed candidates leave both the live client and its resources untouched. */
export async function publishClient({ filename, source, smokeTest, beforePublish }) {
  validateClient(source, { filename, smokeTest })
  if (beforePublish !== undefined) await beforePublish()
  if (existsSync(filename)) {
    const previous = readFileSync(filename, 'utf8')
    if (previous === source) return false
    let previousIsValid = false
    try {
      validateClient(previous, { filename, smokeTest })
      previousIsValid = true
    } catch {
      // Never replace the recovery copy with an already broken live artifact.
    }
    if (previousIsValid) await writeAtomic(join(dirname(filename), '.build', 'client.previous.js'), previous)
  }
  return writeAtomic(filename, source)
}

/** Detect edits made by another developer while esbuild and smoke tests were running. */
export function fingerprintSources(directory) {
  const hash = createHash('sha256')
  function visit(folder) {
    for (const entry of readdirSync(folder, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const filename = join(folder, entry.name)
      hash.update(filename)
      if (entry.isDirectory()) visit(filename)
      else hash.update(readFileSync(filename))
    }
  }
  visit(directory)
  return hash.digest('hex')
}

/** Multiple Creator tasks must not publish the same Reader artifact concurrently. */
export function acquireBuildLock(root) {
  const filename = join(root, '.build', 'build.lock')
  mkdirSync(dirname(filename), { recursive: true })
  const record = JSON.stringify({ pid: process.pid, id: randomUUID() })
  try {
    writeFileSync(filename, record, { flag: 'wx' })
  } catch (error) {
    if (error.code !== 'EEXIST') throw error
    let previous
    let owner
    try {
      previous = readFileSync(filename, 'utf8')
      owner = JSON.parse(previous).pid
    } catch {
      throw new Error('Reader build lock is unreadable; another build may be starting. Retry shortly.')
    }
    let exited = false
    if (Number.isSafeInteger(owner) && owner > 0) {
      try { process.kill(owner, 0) } catch (probeError) { exited = probeError.code === 'ESRCH' }
    }
    if (!exited || readFileSync(filename, 'utf8') !== previous) {
      throw new Error(`A Reader build is already running (pid ${owner}); retry after it finishes.`)
    }
    rmSync(filename)
    writeFileSync(filename, record, { flag: 'wx' })
  }
  return () => {
    if (existsSync(filename) && readFileSync(filename, 'utf8') === record) rmSync(filename)
  }
}
